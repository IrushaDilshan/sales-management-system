export const translateCategoryName = (name, lang) => {
  if (!name || lang === 'en') return name;
  const lower = name.toLowerCase();
  if (lower.includes('milk') || lower.includes('dairy')) {
    return lang === 'si' ? 'කිරි සහ කිරි නිෂ්පාදන' : 'பால் மற்றும் பால் பொருட்கள்';
  }
  if (lower.includes('meat') || lower.includes('poultry')) {
    return lang === 'si' ? 'කුකුළු මස් සහ මස් වර්ග' : 'கோழி மற்றும் இறைச்சி வகைகள்';
  }
  if (lower.includes('agro') || lower.includes('coconut')) {
    return lang === 'si' ? 'කෘෂි නිෂ්පාදන' : 'வேளாண் உற்பத்திகள்';
  }
  return name;
};
